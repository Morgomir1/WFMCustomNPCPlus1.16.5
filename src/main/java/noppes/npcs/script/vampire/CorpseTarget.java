package noppes.npcs.script.vampire;

public final class CorpseTarget {
    public final String uuid;
    public final double x;
    public final double y;
    public final double z;

    public CorpseTarget(final String uuid, final double x, final double y, final double z) {
        this.uuid = uuid;
        this.x = x;
        this.y = y;
        this.z = z;
    }
}
